// Builds src/icons/emojiIcons.generated.js: cartoon SVG artwork (Microsoft Fluent Emoji "Flat", MIT) for every emoji used in the app.
// Run: npm run build:icons   (only needed when a new emoji is introduced)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const collection = require('@iconify-json/fluent-emoji-flat/icons.json');
const emojiData = require('unicode-emoji-json');
const root = path.resolve(import.meta.dirname, '..', '..');

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  if (e.isDirectory()) return e.name === 'node_modules' || e.name === 'dist' ? [] : walk(p);
  return /\.(jsx?|json)$/.test(e.name) && !e.name.includes('generated') ? [p] : [];
});

const pat = /\p{Extended_Pictographic}(?:️|‍\p{Extended_Pictographic}️?|\p{Emoji_Modifier})*/gu;
const found = new Set();
for (const f of [...walk(path.join(root, 'frontend/src')), ...walk(path.join(root, 'backend/src'))]) {
  for (const m of fs.readFileSync(f, 'utf8').match(pat) || []) found.add(m);
}
// Emoji with no art in the set (or that are plain symbols) fall back to a close cartoon cousin.
const ALIASES = { '⚠': '⚠️', '✓': null, '☕': '☕', '⏳': '⏳', '⚙': '⚙️', '✏': '✏️', '❤': '❤️', '✈': '✈️', '⏱': '⏱️', '🛡': '🛡️', '🗺': '🗺️', '🏎': '🏎️', '🛠': '🛠️', '🗓': '🗓️' };

const strip = (e) => e.replace(/️/g, '');
const lookup = {};
for (const [char, info] of Object.entries(emojiData)) lookup[strip(char)] = info.slug;

const out = {};
const missing = [];
for (const raw of [...found].sort()) {
  const key = strip(ALIASES[raw] === null ? raw : raw);
  const slug = lookup[key];
  const icon = slug && collection.icons[slug.replace(/_/g, '-')];
  if (!icon) { missing.push(`${raw} (${slug || 'no slug'})`); continue; }
  // Namespace ids so artwork from different icons can never clash when inlined on one page.
  const tag = `i${Object.keys(out).length}`;
  out[key] = icon.body.replace(/\bid="([^"]+)"/g, `id="${tag}-$1"`).replace(/url\(#([^)]+)\)/g, `url(#${tag}-$1)`).replace(/(xlink:)?href="#([^"]+)"/g, `$1href="#${tag}-$2"`);
}
const header = '// GENERATED by scripts/build-emoji-icons.mjs. Artwork: Microsoft Fluent Emoji (Flat), MIT License.\n';
fs.writeFileSync(path.join(root, 'frontend/src/icons/emojiIcons.generated.js'), `${header}export const ICON_SIZE = ${collection.width || 32};\nexport const ICONS = ${JSON.stringify(out)};\n`);
console.log(`icons: ${Object.keys(out).length}/${found.size}`);
if (missing.length) console.log('no artwork for:', missing.join(', '));
